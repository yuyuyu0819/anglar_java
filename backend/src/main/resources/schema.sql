-- ============================================================================
--  テーブル定義（H2 用）
--
--  spring.sql.init.mode=always により、アプリ起動時に毎回このSQLが実行される。
--  インメモリDBなので起動のたびに作り直される前提で DROP から書いている。
--
--  実案件では Flyway / Liquibase といったマイグレーションツールで
--  DDLをバージョン管理するのが一般的（DDLを手で流す運用は事故が起きやすい）。
-- ============================================================================

DROP TABLE IF EXISTS application;
DROP TABLE IF EXISTS application_category;

-- ----------------------------------------------------------------------------
-- 申請区分マスタ
-- ----------------------------------------------------------------------------
CREATE TABLE application_category (
    code          VARCHAR(10)  NOT NULL,  -- 区分コード
    name          VARCHAR(100) NOT NULL,  -- 区分名
    display_order INT          NOT NULL,  -- 表示順
    CONSTRAINT pk_application_category PRIMARY KEY (code)
);

-- ----------------------------------------------------------------------------
-- 申請
-- ----------------------------------------------------------------------------
CREATE TABLE application (
    -- GENERATED BY DEFAULT AS IDENTITY は標準SQLの自動採番指定。
    -- MySQL の AUTO_INCREMENT / Oracle のシーケンスに相当する
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    application_no  VARCHAR(20)   NOT NULL,  -- 申請番号（例: APP-2026-00001）
    applicant_name  VARCHAR(100)  NOT NULL,  -- 申請者氏名
    applicant_email VARCHAR(255)  NOT NULL,  -- 申請者メールアドレス
    category_code   VARCHAR(10)   NOT NULL,  -- 申請区分コード
    status          VARCHAR(20)   NOT NULL,  -- ステータス（enum名を格納）
    applied_on      DATE          NOT NULL,  -- 申請日
    note            VARCHAR(1000),           -- 備考
    version         INT           NOT NULL DEFAULT 1,  -- 楽観ロック用バージョン
    created_at      TIMESTAMP     NOT NULL,  -- 登録日時
    updated_at      TIMESTAMP     NOT NULL,  -- 更新日時
    CONSTRAINT pk_application PRIMARY KEY (id),
    -- 申請番号は業務上の一意キー。アプリ側のチェックだけに頼らずDB制約で担保する
    CONSTRAINT uk_application_no UNIQUE (application_no),
    CONSTRAINT fk_application_category
        FOREIGN KEY (category_code) REFERENCES application_category (code)
);

-- 検索条件になる列にはインデックスを張る。
-- 官公庁案件はデータ量が多くなりがちで、一覧検索の性能が課題になりやすい
CREATE INDEX idx_application_status ON application (status);
CREATE INDEX idx_application_applied_on ON application (applied_on);
CREATE INDEX idx_application_applicant_name ON application (applicant_name);

-- 列コメントを残したい場合は COMMENT ON 文を使う（H2 / PostgreSQL / Oracle 共通）
COMMENT ON TABLE application IS '申請';
COMMENT ON COLUMN application.application_no IS '申請番号';
COMMENT ON COLUMN application.version IS '楽観ロック用バージョン';
